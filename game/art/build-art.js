// Packs every SVG in ./svg into ../art.js as window.ART = { key: { svg, w, h } },
// and makes one hero per player colour by swapping the suit colours.
//   node build-art.js
const fs = require('fs');
const path = require('path');

const SVG_DIR = path.join(__dirname, 'svg');
const OUT = path.join(__dirname, '..', 'art.js');

// The blue hero's suit colours, in this order: suit light, suit base, suit mid, suit dark,
// back arm, front arm, arm highlight, leg highlight, rim light.
const HERO_BLUE = ['#9cc8ff', '#4f86da', '#2d58a8', '#1f3f80', '#24478c', '#3a6cc4', '#8cbaf7', '#6f9fe6', '#7fb0f5'];
const HERO_VARIANTS = {
  blue: HERO_BLUE,
  green: ['#b6f5a0', '#4cbf5a', '#2e8a3c', '#1f5f2a', '#276b31', '#3fa84d', '#a5ef9a', '#7bd982', '#8fe39a'],
  pink: ['#ffc2e0', '#e8559a', '#b8306e', '#7f1f4c', '#9a2a5d', '#d64a8c', '#ffb3d6', '#f08cbc', '#ff9fca'],
  gold: ['#fff0a8', '#f2c230', '#c48a12', '#8a5c0a', '#9e700f', '#e0b028', '#ffe58a', '#f5d368', '#ffe08a'],
};

const art = {};
for (const file of fs.readdirSync(SVG_DIR).filter((f) => f.endsWith('.svg')).sort()) {
  const key = file.replace(/\.svg$/, '');
  const svg = fs.readFileSync(path.join(SVG_DIR, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
  const m = svg.match(/width="(\d+)" height="(\d+)"/);
  const entry = { svg, w: Number(m[1]), h: Number(m[2]) };
  if (key === 'player') {
    for (const [name, colours] of Object.entries(HERO_VARIANTS)) {
      let s = svg;
      HERO_BLUE.forEach((c, i) => { s = s.split(c).join(`@@${i}@@`); });
      colours.forEach((c, i) => { s = s.split(`@@${i}@@`).join(c); });
      art[`player-${name}`] = { ...entry, svg: s };
    }
  } else {
    art[key] = entry;
  }
}

fs.writeFileSync(OUT, '// Generated by art/build-art.js from art/svg/*.svg. Do not edit by hand.\nwindow.ART = ' + JSON.stringify(art) + ';\n');
console.log('wrote', OUT, Object.keys(art).join(', '));
